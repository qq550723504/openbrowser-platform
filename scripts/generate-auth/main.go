// Generates the typed Wails boundary from the original App signatures.
// Run from the repository root: go run ./scripts/generate-auth
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func must(err error) {
	if err != nil {
		panic(err)
	}
}
func main() {
	fset := token.NewFileSet()
	files, err := filepath.Glob("backend/*.go")
	must(err)
	methods := map[string]*ast.FuncDecl{}
	imports := map[string]string{}
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		must(err)
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || !fn.Name.IsExported() {
				continue
			}
			star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			ident, ok := star.X.(*ast.Ident)
			if !ok || ident.Name != "App" {
				continue
			}
			methods[fn.Name.Name] = fn
			for _, imp := range f.Imports {
				path, err := strconv.Unquote(imp.Path.Value)
				must(err)
				alias := filepath.Base(path)
				if imp.Name != nil {
					alias = imp.Name.Name
				}
				imports[alias] = path
			}
		}
	}
	expr := func(n ast.Node) string { var b bytes.Buffer; must(printer.Fprint(&b, fset, n)); return b.String() }
	names := make([]string, 0, len(methods))
	for n := range methods {
		names = append(names, n)
	}
	sort.Strings(names)
	var body strings.Builder
	type binding struct {
		Arguments int    `json:"arguments"`
		Policy    string `json:"policy"`
	}
	policy := map[string]binding{
		"QuitAppOnly": {0, "cleanup"}, "CloseOwnedBrowser": {1, "cleanup"},
		"AuthStatus": {0, "auth"}, "AuthLogin": {1, "auth"}, "AuthCancel": {1, "auth"}, "AuthLogout": {1, "auth"}, "AuthGrantAPI": {2, "auth"},
	}
	used := map[string]bool{}
	for _, name := range names {
		if name == "GetInterceptor" || name == "QuitAppOnly" {
			continue
		} // internal handle; explicit safe exit
		fn := methods[name]
		var params, args, rets, outs []string
		for _, f := range fn.Type.Params.List {
			typ := expr(f.Type)
			for _, n := range f.Names {
				params = append(params, n.Name+" "+typ)
				args = append(args, n.Name)
			}
		}
		hasError := false
		if fn.Type.Results != nil {
			for _, f := range fn.Type.Results.List {
				typ := expr(f.Type)
				count := len(f.Names)
				if count == 0 {
					count = 1
				}
				for i := 0; i < count; i++ {
					rets = append(rets, typ)
				}
			}
		}
		if len(rets) > 0 && rets[len(rets)-1] == "error" {
			hasError = true
		}
		originalCount := len(rets)
		if !hasError {
			rets = append(rets, "error")
		}
		for i, typ := range rets {
			outs = append(outs, fmt.Sprintf("r%d %s", i, typ))
		}
		params = append(params, "generation uint64")
		policy[name] = binding{len(params), "protected"}
		signature := strings.Join(params, ", ") + strings.Join(rets, ", ")
		for alias := range imports {
			if strings.Contains(signature, alias+".") {
				used[alias] = true
			}
		}
		fmt.Fprintf(&body, "func (a *AuthBoundApp) %s(%s) (%s) {\n", name, strings.Join(params, ", "), strings.Join(outs, ", "))
		fmt.Fprintf(&body, "core, authErr := a.scoped(generation); if authErr != nil { r%d = authErr; return }\n", len(rets)-1)
		if name == "BrowserProfilePackageImportWithOptions" {
			body.WriteString("if r1 = core.requireImportPreview(zipPath,generation); r1 != nil { return }\n")
		}
		var assigned []string
		for i := 0; i < originalCount; i++ {
			assigned = append(assigned, fmt.Sprintf("r%d", i))
		}
		if len(assigned) > 0 {
			fmt.Fprintf(&body, "%s = ", strings.Join(assigned, ", "))
		}
		fmt.Fprintf(&body, "core.%s(%s)\n", name, strings.Join(args, ", "))
		body.WriteString("return\n}\n\n")
	}
	var source strings.Builder
	source.WriteString("// Code generated by scripts/generate-auth; DO NOT EDIT.\npackage backend\n\nimport (\n")
	aliases := make([]string, 0, len(used))
	for a := range used {
		aliases = append(aliases, a)
	}
	sort.Strings(aliases)
	for _, a := range aliases {
		fmt.Fprintf(&source, "%s %q\n", a, imports[a])
	}
	source.WriteString(")\n\n")
	source.WriteString(body.String())
	formatted, err := format.Source([]byte(source.String()))
	must(err)
	must(os.WriteFile("backend/auth_bound_generated.go", formatted, 0644))

	// SDK declarations stay Wails-owned. The adapter derives business argument
	// types by removing the final generation added by this boundary.
	var ts strings.Builder
	ts.WriteString("// Code generated by scripts/generate-auth; DO NOT EDIT.\nimport * as Native from '../wailsjs/go/main/App';\nimport { callBusiness, captureBusiness } from './session';\ntype Args<F> = F extends (...args: infer A) => unknown ? A extends [...infer B, number] ? B : never : never;\n")
	for _, n := range names {
		if n == "GetInterceptor" {
			continue
		}
		if n == "QuitAppOnly" {
			ts.WriteString("export const QuitAppOnly = Native.QuitAppOnly;\n")
			continue
		}
		fmt.Fprintf(&ts, "export const %s = (...args: Args<typeof Native.%s>): ReturnType<typeof Native.%s> => callBusiness(Native.%s, args) as ReturnType<typeof Native.%s>;\n", n, n, n, n, n)
	}
	ts.WriteString("\nconst businessBindings = {\n")
	for _, n := range names {
		if n != "GetInterceptor" {
			fmt.Fprintf(&ts, "  %s,\n", n)
		}
	}
	ts.WriteString("};\nexport function captureBridge(invoke = captureBusiness()): typeof businessBindings {\n  const bound = {} as typeof businessBindings;\n  for (const name of Object.keys(businessBindings) as (keyof typeof businessBindings)[]) {\n    const method = Native[name];\n    (bound as Record<string, unknown>)[name] = name === 'QuitAppOnly' ? method : (...args: unknown[]) => invoke(method, args);\n  }\n  return bound;\n}\n")
	must(os.MkdirAll("frontend/src/auth", 0755))
	must(os.WriteFile("frontend/src/auth/bridge.ts", []byte(ts.String()), 0644))
	encoded, err := json.MarshalIndent(policy, "", "  ")
	must(err)
	must(os.WriteFile("frontend/src/auth/bindings.json", append(encoded, '\n'), 0644))
}
