// Offline SDK bootstrap; normal Wails regeneration yields the same signatures.
// Parse TypeScript so generic type commas never become extra parameters.
import fs from 'node:fs';
import ts from 'typescript';
const base = new URL('../src/wailsjs/go/main/', import.meta.url);
const policy = JSON.parse(fs.readFileSync(new URL('../src/auth/bindings.json', import.meta.url), 'utf8'));
let declarations = fs.readFileSync(new URL('App.d.ts', base), 'utf8');
const parsed = ts.createSourceFile('App.d.ts', declarations, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const edits = [], found = new Set();
for (const statement of parsed.statements) {
  if (!ts.isFunctionDeclaration(statement) || !statement.name) continue;
  const name = statement.name.text;
  if (name === 'GetInterceptor') { edits.push({ start: statement.getStart(), end: statement.end, text: '' }); continue; }
  const entry = policy[name];
  if (!entry) throw new Error(`Unclassified SDK binding: ${name}`);
  found.add(name);
  if (statement.parameters.length === entry.arguments) continue;
  if (entry.policy !== 'protected' || statement.parameters.length + 1 !== entry.arguments) throw new Error(`SDK arity mismatch: ${name}`);
  edits.push({ start: statement.parameters.end, end: statement.parameters.end, text: `${statement.parameters.length ? ',' : ''}generation:number` });
}
for (const edit of edits.sort((a,b) => b.start-a.start)) declarations = declarations.slice(0,edit.start)+edit.text+declarations.slice(edit.end);
const status = 'Promise<{generation:number;state:string;configured:boolean;subject?:string;issuer?:string;expiresAt?:string;errorCode?:string;apiGranted?:boolean}>';
const extras = { AuthStatus: `():${status}`, AuthLogin: `(generation:number):${status}`, AuthCancel: `(generation:number):${status}`, AuthLogout: `(generation:number):${status}`, AuthGrantAPI: '(generation:number,enabled:boolean):Promise<void>', CloseOwnedBrowser: '(profileID:string):Promise<void>' };
for (const [name, signature] of Object.entries(extras)) if (!found.has(name)) { declarations += `\nexport function ${name}${signature};\n`; found.add(name); }
if (Object.keys(policy).some(name => !found.has(name))) throw new Error('SDK is missing a classified binding');
fs.writeFileSync(new URL('App.d.ts', base), declarations);
const js = Object.keys(policy).sort().map(name => {
  const args = Array.from({length:policy[name].arguments},(_,index)=>`arg${index+1}`).join(', ');
  return `export function ${name}(${args}) { return window['go']['main']['App']['${name}'](${args}); }`;
}).join('\n');
fs.writeFileSync(new URL('App.js', base), `// Generated offline from AuthBoundApp; regenerated by Wails.\n${js}\n`);
